import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {canonicalExternalUrl,inspectPublicEvidence,cleanDeliverable,qaSummary,QA_ITEMS} from '../hybrid.mjs';
for(const url of ['http://trustpilot.com/review/pawfecthouse.com','https://trustpilot.com.evil.test/review/pawfecthouse.com','https://127.0.0.1/admin','https://www.etsy.com/','https://www.reddit.com/'])assert.throws(()=>canonicalExternalUrl(url),'Reject unsafe or nonspecific external URL');
assert.equal(canonicalExternalUrl('https://www.trustpilot.com/review/pawfecthouse.com?utm_source=test'),'https://www.trustpilot.com/review/pawfecthouse.com');
const fakeFetch=async(url,opts)=>{
 assert.equal(opts.redirect,'error');
 assert.match(url,/trustpilot.com/);
 return {ok:true,headers:{get:k=>k==='content-type'?'text/html':'440'},text:async()=>'<html><head><meta property="og:title" content="PawfectHouse Reviews"><meta name="description" content="Visitor submitted feedback index"></head></html>'};
};
const evidence=await inspectPublicEvidence('https://www.trustpilot.com/review/pawfecthouse.com',fakeFetch);
assert.equal(evidence.status,'metadata_only');
assert.equal(evidence.title,'PawfectHouse Reviews');
assert.match(evidence.limitations,/No customer review/);
const blocked=await inspectPublicEvidence('https://www.trustpilot.com/review/pawfecthouse.com',async()=>{throw Error('blocked')});
assert.equal(blocked.status,'unavailable');
const d=cleanDeliverable({content:'Copy, subject to verification',materials:[{slot:'banner_desktop',file_id:'',notes:'not generated'}],evidence:[evidence],qa:{product_truth:true}});
assert.equal(d.qa.product_truth,true);
assert.equal(d.qa.desktop,false);
assert.equal(d.materials[0].status,'planned');
assert.equal(qaSummary(d).ready,false);
assert.equal(QA_ITEMS.length,8);
assert.throws(()=>cleanDeliverable({materials:[{slot:'injected</script>',file_id:''}]}));
assert.throws(()=>cleanDeliverable({evidence:[{url:'https://example.com/path'}]}));
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];assert.ok(js);
new vm.Script(js);
assert.match(html,/id="hybridPanel"/);
assert.match(html,/Capture metadata/);
assert.match(html,/Sync result & QA/);
assert.match(html,/data-hybrid-slot/);
assert.match(html,/hybridOverall/);
assert.match(html,/data-hybrid-qa/);
assert.match(html,/API Auto/);
assert.match(html,/pipelineAll/);
const server=await readFile(new URL('../server.mjs',import.meta.url),'utf8');
assert.match(server,/STUDIO_AI_EXECUTOR_ENABLED==='true'/);
assert.match(server,/acknowledge_metered_api/);
assert.match(server,/studio_deliverables/);
assert.match(server,/task.owner_id!==team.id/);
assert.match(server,/material points to a missing task attachment/);
assert.match(server,/const maxBody = 80000/);
console.log('Hybrid evidence safety, manual QA, task sync UI, API gating passed');
