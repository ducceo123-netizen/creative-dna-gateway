import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const server=await readFile(new URL('../server.mjs',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
const dom=new Map(), el=id=>{if(!dom.has(id))dom.set(id,{id,value:'',innerHTML:'',textContent:'',style:{},focus(){}});return dom.get(id);};
const ctx=vm.createContext({document:{getElementById:el,querySelectorAll:()=>[],addEventListener(){}},window:{tt:null},URL,Blob,Date,Promise,clearTimeout,setTimeout,localStorage:{getItem:()=>null,setItem(){}},console,fetch:async()=>({ok:true,json:async()=>({aiConfigured:false,cloudConfigured:true})})});
vm.runInContext(script,ctx,{timeout:1000});
const run=x=>vm.runInContext(x,ctx,{timeout:1000});
assert.match(run('loginScreen()'),/Sign in to UID Brands/);
assert.match(run('loginScreen()'),/Create account/);
run('state.signupMode=true');
assert.match(run('loginScreen()'),/Create your workspace account/);
assert.match(run('loginScreen()'),/name@happyuid.com/);
assert.match(run('loginScreen()'),/data-action="signup"/);
assert.match(server,/companySignupSettings\(\)/);
assert.match(server,/mailer_autoconfirm===false/);
assert.match(server,/disable_signup===false/);
assert.match(server,/external\?\.email===true/);
assert.match(server,/user\.data\.email_confirmed_at/);
assert.match(server,/companyEmail\(user\.data\.email\)/);
assert.match(server,/path==='\/api\/auth\/signup'/);
console.log('Verified company signup UI and backend security gates passed');
