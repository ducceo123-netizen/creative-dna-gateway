import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];assert.ok(script);
const server=await readFile(new URL('../server.mjs',import.meta.url),'utf8');
const dom=new Map(),el=id=>{if(!dom.has(id))dom.set(id,{id,value:'',innerHTML:'',textContent:'',style:{},focus(){}});return dom.get(id)};
const ctx=vm.createContext({document:{getElementById:el,querySelectorAll:()=>[],addEventListener(){}},window:{tt:null,open(){}},URL,Blob,Date,Promise,clearTimeout,setTimeout,localStorage:{getItem:()=>null,setItem(){}},console,fetch:async()=>({ok:true,json:async()=>({aiConfigured:false,cloudConfigured:false})})});
vm.runInContext(script,ctx,{timeout:1000});
const run=expression=>vm.runInContext(expression,ctx,{timeout:1000});
const home=run('dashboard()');
for(const x of ['API Auto','ChatGPT Connect','Hybrid Bridge','awaiting approval'])assert.ok(home.toLowerCase().includes(x.toLowerCase()),x);
assert.match(home,/data-execution-mode="api_auto"/);
assert.match(home,/data-execution-mode="hybrid_bridge"/);
assert.match(home,/data-execution-mode="chatgpt_connect"[^>]+disabled/);
assert.match(home,/aria-pressed="true"/);
assert.match(run('settings()'),/Execution Mode|EXECUTION MODE/);
assert.match(run('taskEditor({id:"UID-TEST",title:"Test",brand:"PawfectHouse",workflow:"Onepage",url:"",brief:"test",content:"",feedback:"",status:"Draft"})'),/data-execution-mode="api_auto"/);
run("state.executionMode='api_auto'");
assert.match(run('dashboard()'),/API Auto selected, but server API is not configured/);
assert.match(run('hybridMarkup("UID-TEST")'),/Run API Auto/);
run("state.executionMode='hybrid_bridge'");
assert.match(run('hybridMarkup("UID-TEST")'),/Copy ChatGPT handoff/);
assert.match(server,/studio_execution_preferences/);
assert.match(server,/Select API Auto in Execution Mode Switcher/);
assert.match(server,/if\(mode==='chatgpt_connect'&&!PLAN_GATEWAY_APPROVED\)/);
assert.match(server,/if\(input\?\.acknowledge_metered_api!==true\)/);
assert.match(server,/STUDIO_AI_EXECUTOR_ENABLED==='true'/);
console.log('Execution mode UI, account preferences, locked plan gateway and metered API guard passed');
